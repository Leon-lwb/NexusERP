-- Flowable 7.0.0 数据库表结构说明
-- 
-- Flowable 会在应用首次启动时自动创建所需的数据库表
-- 如果需要手动创建，可以执行以下操作：
-- 
-- 1. 方式一：配置自动创建
--    在 application.yml 中添加：
--    flowable:
--      database-schema-update: true
-- 
-- 2. 方式二：手动执行官方SQL脚本
--    从 Flowable 官方下载对应版本的 SQL 脚本
--    或从以下路径获取：
--    nbmade-boot/script/sql/mysql/flowable_6.7.2_mysql(首次启动程序未自动生成表，可执行此脚本).sql
-- 
-- Flowable 核心表说明：
-- 
-- 通用数据表 (ACT_GE_*)
--   ACT_GE_PROPERTY - 属性数据表
--   ACT_GE_BYTEARRAY - 二进制数据表
-- 
-- 流程定义表 (ACT_RE_*)
--   ACT_RE_DEPLOYMENT - 部署信息表
--   ACT_RE_MODEL - 模型信息表
--   ACT_RE_PROCDEF - 流程定义数据表
-- 
-- 运行时数据表 (ACT_RU_*)
--   ACT_RU_EXECUTION - 运行时流程执行实例表
--   ACT_RU_TASK - 运行时任务表
--   ACT_RU_VARIABLE - 运行时变量表
--   ACT_RU_IDENTITYLINK - 运行时身份链接表
--   ACT_RU_EVENT_SUBSCR - 运行时事件订阅表
--   ACT_RU_JOB - 运行时作业表
-- 
-- 历史数据表 (ACT_HI_*)
--   ACT_HI_PROCINST - 历史流程实例表
--   ACT_HI_ACTINST - 历史活动实例表
--   ACT_HI_TASKINST - 历史任务实例表
--   ACT_HI_VARINST - 历史变量实例表
--   ACT_HI_COMMENT - 历史评论表
--   ACT_HI_ATTACHMENT - 历史附件表
--   ACT_HI_IDENTITYLINK - 历史身份链接表
--   ACT_HI_DETAIL - 历史详情表
-- 
-- 其他表
--   ACT_EVT_LOG - 事件日志表
--   ACT_PROCDEF_INFO - 流程定义信息表
