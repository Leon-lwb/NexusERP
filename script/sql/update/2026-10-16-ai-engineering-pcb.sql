CREATE TABLE ai_engineering_device (
  `device_id` bigint NOT NULL COMMENT '设备编号',
  `tenant_id` varchar(20) COLLATE utf8mb4_bin NOT NULL DEFAULT '000000' COMMENT '租户编号，保留前导零',
  `user_id` bigint NOT NULL COMMENT '所有者用户编号',
  `device_name` varchar(120) NOT NULL DEFAULT '' COMMENT '设备显示名称',
  `status` varchar(20) NOT NULL DEFAULT 'ACTIVE' COMMENT '设备状态',
  `access_hash` varchar(64) DEFAULT NULL COMMENT '访问凭证摘要',
  `refresh_hash` varchar(64) DEFAULT NULL COMMENT '刷新凭证摘要',
  `generation` bigint NOT NULL DEFAULT 1 COMMENT '凭证代数',
  `access_expires_at` datetime DEFAULT NULL COMMENT '访问凭证到期时间',
  `refresh_expires_at` datetime DEFAULT NULL COMMENT '刷新凭证到期时间',
  `credential_fingerprint` varchar(64) DEFAULT NULL COMMENT '配对时认证状态内部摘要',
  `capabilities` mediumtext DEFAULT NULL COMMENT '设备实际能力与版本',
  `allowed_capabilities` mediumtext DEFAULT NULL COMMENT '配对允许能力集合',
  `last_heartbeat` datetime DEFAULT NULL COMMENT '最近心跳时间',
  `busy_task_id` bigint DEFAULT NULL COMMENT '正在执行的任务',
  `created_at` datetime DEFAULT NULL COMMENT '创建时间',
  `create_dept` bigint DEFAULT NULL COMMENT '创建部门',
  `create_by` bigint DEFAULT NULL COMMENT '创建用户',
  `create_time` datetime DEFAULT NULL COMMENT '创建审计时间',
  `update_by` bigint DEFAULT NULL COMMENT '修改用户',
  `update_time` datetime DEFAULT NULL COMMENT '修改审计时间',
  PRIMARY KEY (`device_id`),
  UNIQUE KEY uk_engineering_device_access (access_hash),
  UNIQUE KEY uk_engineering_device_refresh (refresh_hash),
  KEY idx_engineering_device_owner (tenant_id,user_id,status,last_heartbeat)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC COMMENT='AI工程设备';

CREATE TABLE ai_engineering_task (
  `task_id` bigint NOT NULL COMMENT '任务编号',
  `tenant_id` varchar(20) COLLATE utf8mb4_bin NOT NULL DEFAULT '000000' COMMENT '租户编号',
  `user_id` bigint NOT NULL COMMENT '任务所有者',
  `device_id` bigint NOT NULL COMMENT '指定执行设备',
  `session_id` bigint DEFAULT NULL COMMENT '关联会话编号',
  `request_id` varchar(128) COLLATE utf8mb4_bin DEFAULT NULL COMMENT '服务端聊天请求标识',
  `parent_task_id` bigint DEFAULT NULL COMMENT '原任务编号',
  `action` varchar(32) NOT NULL COMMENT '受控动作',
  `idempotency_key` varchar(160) COLLATE utf8mb4_bin NOT NULL COMMENT '用户作用域幂等键',
  `request_hash` varchar(64) NOT NULL COMMENT '规范请求摘要',
  `request_json` mediumtext DEFAULT NULL COMMENT '有界结构化请求',
  `state` varchar(32) NOT NULL COMMENT '任务状态',
  `stage` varchar(32) DEFAULT NULL COMMENT '当前阶段',
  `attempt` int NOT NULL DEFAULT 0 COMMENT '领取尝试编号',
  `revision` bigint NOT NULL DEFAULT 0 COMMENT '比较交换修订号',
  `lease_hash` varchar(64) DEFAULT NULL COMMENT '租约凭证摘要',
  `lease_expires_at` datetime DEFAULT NULL COMMENT '租约到期时间',
  `deadline_at` datetime DEFAULT NULL COMMENT '运行截止时间',
  `waiting_expires_at` datetime DEFAULT NULL COMMENT '等待设备截止时间',
  `cancel_requested` boolean NOT NULL DEFAULT FALSE COMMENT '运行取消请求',
  `step_journal` mediumtext DEFAULT NULL COMMENT '有界步骤回执日志',
  `reserved_bytes` bigint NOT NULL DEFAULT 0 COMMENT '已确认及预留字节总量',
  `reserved_files` int NOT NULL DEFAULT 0 COMMENT '已确认及预留文件数量',
  `error_code` varchar(64) DEFAULT NULL COMMENT '安全错误类别',
  `error_message` varchar(2048) DEFAULT NULL COMMENT '中文安全错误摘要',
  `created_at` datetime DEFAULT NULL COMMENT '创建时间',
  `updated_at` datetime DEFAULT NULL COMMENT '修改时间',
  `create_dept` bigint DEFAULT NULL COMMENT '创建部门',
  `create_by` bigint DEFAULT NULL COMMENT '创建用户',
  `create_time` datetime DEFAULT NULL COMMENT '创建审计时间',
  `update_by` bigint DEFAULT NULL COMMENT '修改用户',
  `update_time` datetime DEFAULT NULL COMMENT '修改审计时间',
  PRIMARY KEY (`task_id`),
  UNIQUE KEY uk_engineering_task_owner (tenant_id,user_id,idempotency_key),
  KEY idx_engineering_task_device (tenant_id,user_id,device_id,state),
  KEY idx_engineering_task_expiry (state,lease_expires_at,waiting_expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC COMMENT='AI工程任务';

