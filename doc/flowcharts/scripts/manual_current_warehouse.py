"""Current WM operations omitted from the historical twenty-chapter manual."""


def ch23_warehouse(doc, h1, h2, h3, para, bullet, numbered, table):
    h1(doc, '第23章 仓储管理')
    para(doc, '本章补齐原手册缺少的仓储操作。入口为管理员配置的仓储管理菜单；'
              '菜单名称可以调整，按钮可用性同时受当前租户、权限和单据状态约束。'
              '采购、销售和生产的业务准备分别参见第4、3、6章，质检参见第9章。')

    h2(doc, '23.1 仓储业务总览与基础配置')
    para(doc, '先建立仓库、库区和储位，并核对物料的单位、批次、序列号和需检设置。'
              '物理摆放、上架确认、库存过账是不同动作；保存单据或审批通过不表示库存已增加或扣减。')
    table(doc, ['页面 / 对象', '核对与操作'], [
        ['仓库、库区、储位', '按层级维护编码、名称及启停状态；业务选择有效且属于目标仓库的储位。'],
        ['上架规则、拣货规则', '维护物料与规则匹配条件，按配置推荐库位或批次；推荐结果仍需确认。'],
        ['库存、库存明细', '按物料、仓库、库区、储位和批次核对；可用库存与现存库存、预留数量不能混用。'],
        ['批次、SN、条码', '关联真实物料与来源；打印或识别条码不替代收发存业务过账。'],
        ['三维仓库', '有对应配置时查看仓库/库位空间视图；展示结果不替代库存明细。'],
    ], widths=[4.0, 12.0])
    para(doc, '管理员须分别授权查询、新增、审批、上架和执行；只有 query 权限不能执行库存写操作。')

    h2(doc, '23.2 到货通知与采购入库')
    para(doc, '操作入口：仓储管理 > 到货通知 / 物料入库。先核对采购订单、通知行、实际到货数量和日期，'
              '需检物料必须完成相应 IQC 门禁。实际供应资料不得用订单数量或预计交期自动代填。')
    numbered(doc, '认证订单通过认证工作台核对真实采购来源；普通通道只适用于来源守卫允许的历史单据。'
                   '在到货通知页面核对物料、数量和采购订单，按对应链路创建及审批，不能用普通入口绕过认证。')
    numbered(doc, '在物料入库页面核对主表及入库行。普通历史单据先保存主表与行，未保存的行不能添加上架明细。'
                   '自动生成的收货行实收量初始可为零，必须根据实物填写，不复制订单量。')
    numbered(doc, '进入对应行的上架操作，填写仓库、库区、储位、数量及必要批次；确认目标储位和上架明细数量。')
    numbered(doc, 'APPROVED（待上架）时确认上架，系统保存明细并变为 SHELVED（待入库）；此时仍不等于完成库存过账。')
    numbered(doc, '在允许执行的状态下显式执行入库。普通历史单与认证单分别由专属服务核验和过账。'
                   '刷新原单和库存明细，确认 FINISHED 及库存结果；采购数量回写为 MQ 异步联动。'
                   'IQC 完成不会自动调用执行入库。')
    para(doc, 'IQC 未放行、上架数量不足、库位无效或库存执行失败时，按错误信息处理原单，不绕过门禁。'
              '认证收货单不可套用普通入库的编辑或虚拟库存路径，见下一节。')

    h2(doc, '23.3 认证到货与认证收货工作台')
    para(doc, '在对应页面打开认证工作台。该入口将读取、草稿创建、审批提交、同步、认证上架和实际过账分开确认，'
              '不会自动连续执行所有步骤。不存在真实审批、批次分配或 IQC 资料时，工作台可能保持只读 BLOCKED。')
    numbered(doc, '选择真实对象类型，输入原生订单 / 通知 / 收货 ID，点击读取或刷新原生详情，核对租户、操作者和完整快照。')
    numbered(doc, '依据真实材料输入采购行 ID、精确数量、日期、仓库/库区/储位以及成对的通知 ID 和行 ID；不可用预计资料替代实际资料。')
    numbered(doc, '填写本次操作请求键，人工确认当前意图需要的材料已核对；按权限点击一个明确操作，并检查返回结果。')
    numbered(doc, '遇到 UNKNOWN、超时或结果未确认，先读取原单与 GET 永久恢复结果。不得更换请求键或自动补发未知结果的写操作。')
    para(doc, '关闭弹窗不等于清除未决操作；切换租户、账户或页面后应重新读取作用域。'
              '不要复制会话凭据，也不要把请求 ID 当作业务成功证据。')

    h2(doc, '23.4 销售出库与质量门禁')
    para(doc, '操作入口：仓储管理 > 销售出库。列表可按单号、销售订单、客户、仓库、状态和日期筛选。')
    numbered(doc, '新增草稿，选择真实销售订单、客户、仓库和出库行，保存并提交审批。')
    numbered(doc, 'APPROVED 状态点击确认，转为 CONFIRMED；DRAFT 不可跳过审批直接确认。')
    numbered(doc, '需检物料按业务关联完成 OQC；同时核对各行可用库存、批次、预留和出库数量。')
    numbered(doc, 'CONFIRMED 状态点击完成，执行库存扣减与相应业务回写；刷新单据和库存，确认 COMPLETED。')
    para(doc, '库存不足或质量条件不满足时停止执行，不将实际部分出库冒充整单完成。'
              '出库完成、物流发货、开票和收款是不同业务结果，应分别核对。')

    h2(doc, '23.5 生产领料、退料与完工入库')
    para(doc, '操作入口：仓储管理 > 生产领料 / 生产退料 / 生产入库。领料时可选择工单并从工单带入需求，'
              '但需求量不是实际领用量，库存参考金额也不是最终成本确认。')
    numbered(doc, '在生产领料单选择工单和执行仓库，逐行核对物料、待领数量、库存/批次与库位；需要时使用选库存/换仓。')
    numbered(doc, '保存后按可用按钮执行领料；已执行或短结行不能再次修改并重复执行。库存不足按原业务处理，不伪造数量。')
    numbered(doc, '退料时登记工单、仓库、物料和真实退回数量，关联必要批次/库位；保存后核对实际核销结果。')
    numbered(doc, '生产入库选择工单、成品物料、入库数量和仓位，按当前权限及业务条件执行；不要同时重复手工入库与已成功的自动消息入库。')
    para(doc, '倒冲、MES 完工及委外/返工入库依赖各自消息或服务链路；消息发送或单据保存不表示库存已过账。'
              '发现延迟时先核对原单、库存流水和消息处理记录。')

    h2(doc, '23.6 仓库调拨')
    para(doc, '操作入口：仓储管理 > 调拨单。填写调出/调入仓库、物料、数量、批次及必要库位，保存草稿并提交审批。')
    numbered(doc, '审批通过后核对来源可用库存和目标储位；PC 的执行调拨按钮通常在 APPROVED 状态显示。')
    numbered(doc, '执行成功后检查调出扣减、调入增加及单据状态。若走 PDA 下架通道，还需核对 TAKEN_OFF 与后续过账，不混用重复执行。')
    para(doc, '单据审批和物理搬运不能替代库存调拨执行。错误储位或数量应按批准的纠错流程处理，不能直接改账。')

    h2(doc, '23.7 盘点与差异调整')
    para(doc, '操作入口：仓储管理 > 盘点。建立编号、名称、日期、仓库、库区、明盘/盲盘方式和审批流程。'
              'PC 表格与 PDA 盲盘显示不能混为一谈，盲盘规则需按实际终端核对。')
    numbered(doc, '先保存计划，再生成盘点行；生成的是当时库存范围的盘点依据，不是真实实盘数量。')
    numbered(doc, '逐行录入人工确认的实盘数量并保存，核对差异；零数量也是明确业务事实，不能把空值视为零。')
    numbered(doc, '按本环境审批和业务条件执行过账调整。是否允许执行以服务端校验为准，页面显示按钮不等于已获批准。')
    numbered(doc, '过账后刷新计划、明细和库存流水。已 POSTED 的计划不重新生成盘点行或重复过账。')

    h2(doc, '23.8 预留、库存预警与规则')
    para(doc, '预留页面支持手动预留和相应释放操作，先确认物料、仓库、需求来源和有效条件；'
              '释放预留不是库存扣减。库存预警页面可执行检查并登记处理，预警消除不代表已自动采购到货。')
    para(doc, '按管理授权维护上架和拣货规则；执行前检查规则适用的物料、库位、批次和禁用条件。'
              '库存变更以后应刷新可用量，不以旧页面数值作重复领料依据。')

    h2(doc, '23.9 批次、SN、追溯与库存报表')
    para(doc, '维护批次有效期、质量状态与必要隔离，SN 和条码须对应真实物料与来源。'
              '追溯页面输入支持的查询条件后，可切换树形/列表并查看节点；仓储追溯与 MES 生产履历分别参见第8、21章。')
    para(doc, '库存报表、估值、对账和仓库交接按当前菜单提供的操作使用，先核对业务日期、仓库、数量和计价口径。'
              '数据导出受角色权限约束，不能把导出报表当作财务已关账或库存已完成调整。')

    h2(doc, '23.10 执行失败与异步回写处理')
    table(doc, ['现象', '操作原则'], [
        ['按钮不可用 / 返回无权限', '核对当前租户、角色和对象状态；向管理员申请对应权限，不借用其他账户。'],
        ['保存成功但库存未变化', '区分草稿、审批、上架和执行；查看原单状态与库存流水。'],
        ['库存已入账但订单数量未回写', '核对 MQ、消费与幂等处理记录；禁止重复执行入库来催促回写。'],
        ['请求超时或执行结果未知', '刷新原单并只读核对真实结果；认证单使用永久恢复，不换键补发。'],
        ['IQC/OQC 或批次门禁不满足', '由质检/仓管补齐真实资料并按业务流程处理，禁止直接改为通过。'],
    ], widths=[5.0, 11.0])
    para(doc, '本章说明当前代码的操作边界；没有验证实际生产数据库、权限配置、PDA 真机及 MQ 环境，'
              '不构成生产部署或业务验收结论。')
