    para(doc, '触发时机：销售出库审批通过后MQ自动创建OQC任务。')

    h2(doc, '9.4 质量追溯与不合格品')
    bullet(doc, '质量追溯：批次→检验记录追溯')
    bullet(doc, '不合格品处理：检验不合格→批次隔离→NCR单据→返工工单→8D报告（详见第11章）')

    h2(doc, '9.5 SPC统计过程控制')
    para(doc, '操作入口：质量管理 > SPC控制图')
    para(doc, '控制图类型：X-Bar/R均值-极差图、X-Bar/S均值-标准差图、P不合格品率图、C不合格数图、U单位缺陷数图。')
    para(doc, '表单字段：控制图名称*、图表类型*（默认X_BAR_R）、关联采集点*（SPC数据来源）、样本大小（2-10）、关联物料（可选）、关联工序（可选）、状态。')
    para(doc, '分析功能：ECharts控制图（UCL/CL/LCL控制线，OOC超限点红色标注违规规则）、数据点数统计、OOC点数。')
    para(doc, 'OOC超限自动触发安灯（SnailJob定时检查）；数据点由采集记录自动归档产生（mes/spc/data-point查询页）。')


