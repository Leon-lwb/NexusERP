SQL = Path(__file__).resolve().parents[5] / 'script/sql/ry-erp.sql'
SCHEMA_TEXT = SQL.read_text(encoding='utf-8')


class Expr:
    def __init__(self, raw):
        self.raw = raw


def quote(value):
    if isinstance(value, Expr):
        return value.raw
    if value is None:
        return 'NULL'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(rows, table, key, values):
    match = re.search(r'CREATE TABLE\s+`' + table + r'`\s*\((.*?)\)\s*ENGINE\s*=',
                      SCHEMA_TEXT, re.S | re.I)
    if not match:
        raise ValueError(f'main ERP schema lacks {table}')
    columns = set(re.findall(r'^\s*`([^`]+)`\s+', match.group(1), re.M))
    if not set(values).issubset(columns):
        raise ValueError(f'{table}: invalid columns {set(values) - columns}')
    column_types = dict(re.findall(r'^\s*`([^`]+)`\s+([A-Za-z]+)', match.group(1), re.M))
    for name, value in values.items():
        if isinstance(value, str) and column_types.get(name, '').lower() in (
                'bigint', 'int', 'integer', 'tinyint', 'smallint', 'mediumint'):
            if not re.fullmatch(r'-?[0-9]+', value):
                raise ValueError(f'{table}.{name}: integer column cannot contain text')
    rows.append('INSERT INTO `' + table + '` (' + ', '.join('`' + name + '`' for name in values) + ')\n'
                'SELECT ' + ', '.join(quote(value) for value in values.values()) + '\n'
                f'WHERE {GUARD} AND NOT EXISTS (SELECT 1 FROM `{table}` '
                f'WHERE `{key}` = {quote(values[key])} AND `tenant_id` = {quote(TENANT)});')


def header(name):
    return [f'-- {name}: GENERATED BY scripts/build-seed.py; never run against plus/production.',
            '-- DATABASE() 字面量护栏确保在其他数据库误执行时不产生写入。',
            'START TRANSACTION;']


