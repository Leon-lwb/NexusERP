def reset_script():
    statements = ['-- Reset ONLY owned DEMO-AI-DECISION-* rows in the disposable ERP schema.',
                  f'-- Never remove data outside {SCHEMA}.', 'START TRANSACTION;']
    table_code = [('pu_vendor_evaluation', 'vendor_code'), ('pu_purchase_order_line', 'material_code'),
                  ('pu_purchase_order', 'order_no'), ('prd_capacity_calendar', 'object_code'),
                  ('prd_schedule_task', 'wo_no'), ('prd_schedule_plan', 'plan_no'),
                  ('wm_material_stock', 'material_code'),
                  ('prd_material_requirement_detail', 'material_code'),
                  ('prd_material_requirement', 'requirement_no'), ('prd_work_order', 'wo_no'),
                  ('prd_production_plan', 'plan_no'), ('bd_routing_step', 'process_code'),
                  ('bd_routing', 'routing_code'), ('bd_material', 'material_code'),
                  ('bd_vendor', 'vendor_code'), ('bd_process', 'process_code'),
                  ('bd_workstation', 'workstation_code'), ('bd_workshop', 'workshop_code'),
                  ('wm_warehouse', 'warehouse_code'), ('bd_material_category', 'category_code')]
    for table, code in table_code:
        statements.append(f"DELETE FROM `{table}` WHERE {GUARD} AND `tenant_id` = '{TENANT}' "
                          f"AND `{code}` LIKE '{PREFIX}%';")
    statements.append('COMMIT;')
    return '\n\n'.join(statements) + '\n'


def main():
    cases = [json.loads(line) for line in (ROOT / 'cases.jsonl').read_text(encoding='utf-8').splitlines()]
    if len(cases) != 40 or len({c['bizId'] for c in cases}) != 40:
        raise SystemExit('Need exactly 40 unique fixture IDs before writing SQL')
    master, business = header('Demo master data'), header('Demo business data')
    common_data(master)
    for case in cases:
        demo_rows(case, master, business)
    master.append('COMMIT;')
    business.append('COMMIT;')
    for name, content in [('demo-master-data.sql', '\n\n'.join(master) + '\n'),
                          ('demo-business-data.sql', '\n\n'.join(business) + '\n'),
                          ('reset-demo-data.sql', reset_script())]:
        (ROOT / 'seed' / name).write_text(content, encoding='utf-8')
    print('Rendered DB-guarded master/business/reset SQL for 40 business IDs; not executed.')


if __name__ == '__main__':
    main()
