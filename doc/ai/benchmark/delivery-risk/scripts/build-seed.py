        insert(master, 'bd_routing', 'routing_id',
               dict(routing_id=routing, tenant_id=TENANT, routing_code=code + '-ROUTE',
                    routing_name=f'Demo routing {i:03d}', material_id=product,
                    material_code=code + '-PRODUCT', material_name=f'Demo product {i:03d}',
                    is_current=1, status=1, total_steps=1, effective_date=Expr('CURDATE()'), del_flag='0'))
