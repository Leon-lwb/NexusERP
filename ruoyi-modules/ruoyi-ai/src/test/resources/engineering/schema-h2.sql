CREATE TABLE ai_engineering_device (
  device_id bigint NOT NULL,
  tenant_id varchar(20) NOT NULL DEFAULT '000000',
  user_id bigint NOT NULL,
  device_name varchar(120) NOT NULL DEFAULT '',
  status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  access_hash varchar(64) DEFAULT NULL,
  refresh_hash varchar(64) DEFAULT NULL,
  generation bigint NOT NULL DEFAULT 1,
  access_expires_at datetime DEFAULT NULL,
  refresh_expires_at datetime DEFAULT NULL,
  credential_fingerprint varchar(64) DEFAULT NULL,
  capabilities clob DEFAULT NULL,
  allowed_capabilities clob DEFAULT NULL,
  last_heartbeat datetime DEFAULT NULL,
  busy_task_id bigint DEFAULT NULL,
  created_at datetime DEFAULT NULL,
create_dept bigint DEFAULT NULL,
create_by bigint DEFAULT NULL,
create_time datetime DEFAULT NULL,
update_by bigint DEFAULT NULL,
update_time datetime DEFAULT NULL,
PRIMARY KEY (device_id),
UNIQUE (access_hash),
UNIQUE (refresh_hash)
);
CREATE TABLE ai_engineering_task (
  task_id bigint NOT NULL,
  tenant_id varchar(20) NOT NULL DEFAULT '000000',
  user_id bigint NOT NULL,
  device_id bigint NOT NULL,
  session_id bigint DEFAULT NULL,
  request_id varchar(128) DEFAULT NULL,
  parent_task_id bigint DEFAULT NULL,
  action varchar(32) NOT NULL,
  idempotency_key varchar(160) NOT NULL,
  request_hash varchar(64) NOT NULL,
  request_json clob DEFAULT NULL,
  state varchar(32) NOT NULL,
  stage varchar(32) DEFAULT NULL,
  attempt int NOT NULL DEFAULT 0,
  revision bigint NOT NULL DEFAULT 0,
  lease_hash varchar(64) DEFAULT NULL,
  lease_expires_at datetime DEFAULT NULL,
  deadline_at datetime DEFAULT NULL,
  waiting_expires_at datetime DEFAULT NULL,
  cancel_requested boolean NOT NULL DEFAULT FALSE,
  step_journal clob DEFAULT NULL,
  reserved_bytes bigint NOT NULL DEFAULT 0,
  reserved_files int NOT NULL DEFAULT 0,
  error_code varchar(64) DEFAULT NULL,
  error_message varchar(2048) DEFAULT NULL,
  created_at datetime DEFAULT NULL,
  updated_at datetime DEFAULT NULL,
create_dept bigint DEFAULT NULL,
create_by bigint DEFAULT NULL,
create_time datetime DEFAULT NULL,
update_by bigint DEFAULT NULL,
update_time datetime DEFAULT NULL,
PRIMARY KEY (task_id),
UNIQUE (tenant_id,user_id,idempotency_key)
);
CREATE TABLE ai_engineering_artifact (
  artifact_id bigint NOT NULL,
  tenant_id varchar(20) NOT NULL DEFAULT '000000',
  user_id bigint NOT NULL,
  task_id bigint NOT NULL,
  attempt int NOT NULL,
  artifact_type varchar(32) NOT NULL,
  group_id varchar(64) DEFAULT NULL,
  relative_path varchar(255) NOT NULL,
  service varchar(64) DEFAULT NULL,
  oss_id bigint DEFAULT NULL,
  object_key varchar(255) DEFAULT NULL,
  sha256 varchar(64) NOT NULL,
  size bigint NOT NULL,
  mime_type varchar(100) DEFAULT NULL,
  original_filename varchar(255) DEFAULT NULL,
  status varchar(20) NOT NULL DEFAULT 'RESERVED',
  cleanup_generation bigint NOT NULL DEFAULT 0,
  cleanup_expires_at datetime DEFAULT NULL,
  validation_json clob DEFAULT NULL,
  created_at datetime DEFAULT NULL,
create_dept bigint DEFAULT NULL,
create_by bigint DEFAULT NULL,
create_time datetime DEFAULT NULL,
update_by bigint DEFAULT NULL,
update_time datetime DEFAULT NULL,
PRIMARY KEY (artifact_id),
UNIQUE (tenant_id,task_id,attempt,artifact_type,relative_path)
);